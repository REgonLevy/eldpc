"""Optional check: search for upstream-wheel divergences on a larger shot set.

The verification suite compares the installed upstream ``ldpc`` 2.4.1 wheel with the reference on
the suite's shots and reports every differing shot with its cause (``tie_order`` when an
equal-soft-value group can change the OSD pivot set, ``unexplained`` otherwise). On the default
suite corpora the wheel agreed on every shot. This tool runs the same comparison on a larger,
still-public-seeded shot set of selected problems, to exercise the differing-shot path on real
data.

    python verify/tools/upstream_divergence_check.py \
        --problems bb144_unif_p1e-3_r12_z --configs a03125c3 --shots 20000 --out up.json

The shot set is generated by the suite's corpus builder from the fixed base seed with the given
shot count (a larger shot count is a different, deterministic set). Exit status 0 when the run
completes; the JSON line reports the differing shots and their causes.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

_VERIFY = str(Path(__file__).resolve().parents[1])      # verify/tools/x.py -> verify
if _VERIFY not in sys.path:
    sys.path.insert(0, _VERIFY)

from eldpc_verify import upstream as upstream_mod  # noqa: E402
from eldpc_verify.config import default_cache_root, load_config  # noqa: E402
from eldpc_verify.corpus import ensure_corpus  # noqa: E402
from eldpc_verify.reference import build_reference  # noqa: E402
# The suite's own reference pass and upstream column: the same code the suite runs.
from eldpc_verify.runner import (_decode_reference, _upstream_column,  # noqa: E402
                                 config_string)


def _split(text):
    return [x.strip() for x in text.split(",") if x.strip()] if text else None


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--problems", default="bb144_unif_p1e-3_r12_z",
                        help="comma-separated problem ids")
    parser.add_argument("--configs", default="a03125c3", help="comma-separated preset names")
    parser.add_argument("--shots", type=int, default=20000, help="shots per problem")
    parser.add_argument("--cache", default=None, help="corpus and reference cache")
    parser.add_argument("--out", help="write the JSON result here as well as to stdout")
    args = parser.parse_args(argv)

    import eldpc

    ok, description = upstream_mod.availability()
    if not ok:
        print(f"error: {description}", file=sys.stderr)
        return 2
    cfg = load_config()
    by_id = {p["id"]: p for p in cfg["problems"]}
    problems = _split(args.problems) or ["bb144_unif_p1e-3_r12_z"]
    unknown = [p for p in problems if p not in by_id]
    if unknown:
        parser.error(f"unknown problem ids {unknown}")
    presets = eldpc.presets()
    configs = _split(args.configs) or ["a03125c3"]
    unknown = [c for c in configs if c not in presets]
    if unknown:
        parser.error(f"unknown presets {unknown}")

    cache = Path(args.cache) if args.cache else default_cache_root()
    t0 = time.perf_counter()
    ref_info = build_reference(cache)
    ref_build_seconds = time.perf_counter() - t0

    rows = []
    for pid in problems:
        problem = by_id[pid]
        if problem["shape"]["kind"] == "window":
            parser.error("this check uses full problems only")
        t = time.perf_counter()
        corpus = ensure_corpus(cache, problem, cfg["base_seed"], int(args.shots))
        corpus_seconds = time.perf_counter() - t
        for name in configs:
            params = presets[name]
            cs = config_string(params)
            corr_ref, obs_ref, st_ref, reference_seconds = _decode_reference(
                ref_info.path, cs, corpus)
            upstream = _upstream_column(corpus, params, st_ref, corr_ref, obs_ref,
                                        ref_info.path, lambda *a: None)
            row = {"problem": pid, "config": name, "shots": corpus.shots,
                   "reference_seconds": round(reference_seconds, 3),
                   "upstream": upstream}
            rows.append(row)
            print(f"{pid} / {name}: {corpus.shots} shots, "
                  f"{upstream.get('differing_shots', 0)} differing, "
                  f"causes {upstream.get('causes')}", flush=True)

    result = {
        "schema": "eldpc.verify.upstream_divergence.v1",
        "upstream": description,
        "reference_build_info": ref_info.build_info,
        "reference_build_seconds": round(ref_build_seconds, 3),
        "rows": rows,
        "totals": {
            "shots": sum(r["shots"] for r in rows),
            "differing_shots": sum(r["upstream"].get("differing_shots", 0) for r in rows),
            "causes": {cause: sum(r["upstream"].get("causes", {}).get(cause, 0) for r in rows)
                       for cause in ("tie_order", "unexplained")},
        },
    }
    text = json.dumps(result, sort_keys=True)
    print(text)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
