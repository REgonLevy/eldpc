"""Corpus generation and caching for the verification suite.

A corpus entry is one problem with one shot count, generated from the suite's public base seed.
Its directory holds the decoding problem exactly as the decoder sees it -- H and O in canonical
CSC (column pointers and row indices), priors, the DEM text -- and the sampled shot set (detectors
and true observable flips), plus a manifest with the SHA-256 of every file.

Layout under the cache root::

    corpora/<problem id>/<key>/
        H.indptr.npy H.indices.npy O.indptr.npy O.indices.npy
        priors.npy det_round.npy dets.npy obs.npy dem.txt manifest.json

``key`` is the SHA-256 of the problem object, the base seed, the shot count and the generator: the
qLDPC version (and the git commit it was installed from, when pip recorded one), the stim version and
stim's SIMD backend, which build the circuit, derive the DEM and sample the shots. Changing any of
them produces a fresh entry and leaves the old one alone, so switching qLDPC or stim never reuses a
corpus generated by another version. Entries are written into a temporary
sibling directory and renamed into place; a present entry is reused only when every file matches
its manifest. The arrays are plain ``.npy`` files, whose bytes depend only on the values, so
regenerating an entry from the same seed on the same stim build reproduces it byte for byte.

A problem with ``loss`` inserts heralded erasure before the final readout (adding herald detectors
and mechanisms) before the DEM is derived. A problem with a ``window`` shape is derived from its
parent's cached entry: the detectors of rounds ``[start_round, start_round + w)`` and the
mechanisms whose column of H touches them, with the parent's first shots restricted to those
detector rows; ``det_round.npy`` stores the measurement round of every detector for this.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import sys
from pathlib import Path

import numpy as np

from . import CORPUS_SCHEMA
from . import circuits
from .dem import arrays_to_dem_text, canonical_csc, dem_to_arrays, extract_window

_MANIFEST = "manifest.json"
_ARRAY_FILES = ("H.indptr.npy", "H.indices.npy", "O.indptr.npy", "O.indices.npy",
                "priors.npy", "det_round.npy", "dets.npy", "obs.npy")


class CorpusError(RuntimeError):
    """A corpus entry cannot be built, read or validated."""


def _canonical_json(obj) -> bytes:
    return (json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True) + "\n").encode()


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _stim_simd() -> str:
    """SIMD backend of the loaded stim extension ("sse2", "avx2", "polyfill", ...).

    Stim's seeded sampling is reproducible for one backend; the suite records the backend so a
    corpus manifest says under which one it was produced."""
    import stim  # noqa: F401  (importing stim loads the stim._stim_<backend> extension)

    prefix = "stim._stim_"
    names = sorted(name for name in sys.modules if name.startswith(prefix) and name != prefix)
    return names[0][len(prefix):] if names else "unknown"


def _qldpc_commit() -> str | None:
    """The git commit qLDPC was installed from, from pip's ``direct_url.json``; None otherwise.

    A qLDPC installed from git main carries a date-based development version that two commits of
    one day share, so the commit identifies the revision that built a corpus."""
    try:
        from importlib import metadata

        text = metadata.distribution("qldpc").read_text("direct_url.json")
        info = json.loads(text) if text else {}
    except Exception:  # noqa: BLE001 - no metadata, no record: the version alone identifies it
        return None
    vcs_info = info.get("vcs_info") if isinstance(info, dict) else None
    commit = vcs_info.get("commit_id") if isinstance(vcs_info, dict) else None
    return str(commit) if commit else None


def generator_versions() -> dict:
    """What builds a corpus entry besides the problem, the seed and the shot count.

    qLDPC builds the circuits of the bb/hgp/css problems (another revision can produce another
    circuit, and with it other mechanism counts), stim derives the DEM and samples the shots
    (seeded samples are reproducible for one stim build and SIMD backend). All of it is part of
    the cache key."""
    import qldpc
    import stim

    return {"qldpc": str(qldpc.__version__), "qldpc_commit": _qldpc_commit(),
            "stim": str(stim.__version__), "stim_simd": _stim_simd()}


def describe_generator(generator: dict) -> str:
    """One line naming the qLDPC and stim a corpus was built with."""
    commit = generator.get("qldpc_commit")
    name = f"qLDPC {generator.get('qldpc')}" + (f" (commit {commit[:7]})" if commit else "")
    return f"{name}, stim {generator.get('stim')} ({generator.get('stim_simd')})"


def versions() -> dict:
    import scipy

    return {**generator_versions(), "numpy": np.__version__, "scipy": scipy.__version__}


def corpus_key(problem: dict, base_seed: int, shots: int, generator: dict | None = None) -> str:
    """Cache key of one corpus entry; ``generator`` defaults to the installed generator_versions()."""
    payload = {"schema": CORPUS_SCHEMA, "problem": problem, "base_seed": int(base_seed),
               "shots": int(shots),
               "generator": generator_versions() if generator is None else generator}
    return _sha256_bytes(_canonical_json(payload))


def corpus_dir(cache_root, problem: dict, base_seed: int, shots: int,
               generator: dict | None = None) -> Path:
    return Path(cache_root) / "corpora" / problem["id"] / corpus_key(problem, base_seed, shots,
                                                                      generator)


class Corpus:
    """One generated problem and shot set."""

    def __init__(self, problem: dict, H, O, priors, det_round, dets, obs, dem_text: str,
                 manifest: dict, path: Path | None = None, from_cache: bool = False):
        self.problem = problem
        self.H = H
        self.O = O
        self.priors = priors
        self.det_round = det_round
        self.dets = dets
        self.obs = obs
        self.dem_text = dem_text
        self.manifest = manifest
        self.path = path
        self.from_cache = from_cache

    @property
    def id(self) -> str:
        return self.problem["id"]

    @property
    def num_detectors(self) -> int:
        return int(self.H.shape[0])

    @property
    def num_mechanisms(self) -> int:
        return int(self.H.shape[1])

    @property
    def num_observables(self) -> int:
        return int(self.O.shape[0])

    @property
    def shots(self) -> int:
        return int(self.dets.shape[0])

    def describe(self) -> str:
        return (f"{self.id}: {self.shots} shots, m={self.num_detectors}, "
                f"n={self.num_mechanisms}, k={self.num_observables}")


def _write_files(dest: Path, problem: dict, base_seed: int, shot_seed: int, shots: int,
                 Hc, Oc, priors, det_round, dets, obs, dem_text: str, extra: dict,
                 generator: dict) -> Corpus:
    """Write one entry (arrays, DEM text, manifest) atomically and return it."""
    m = int(Hc.shape[0])
    arrays = {
        "H.indptr.npy": np.ascontiguousarray(Hc.indptr, dtype=np.int32),
        "H.indices.npy": np.ascontiguousarray(Hc.indices, dtype=np.int32),
        "O.indptr.npy": np.ascontiguousarray(Oc.indptr, dtype=np.int32),
        "O.indices.npy": np.ascontiguousarray(Oc.indices, dtype=np.int32),
        "priors.npy": np.ascontiguousarray(priors, dtype=np.float64),
        "det_round.npy": np.ascontiguousarray(det_round, dtype=np.uint32),
        "dets.npy": np.ascontiguousarray(dets, dtype=np.uint8),
        "obs.npy": np.ascontiguousarray(obs, dtype=np.uint8),
    }
    tmp = dest.parent / f"{dest.name}.tmp.{os.getpid()}"
    if tmp.exists():
        shutil.rmtree(tmp)
    tmp.mkdir(parents=True)
    try:
        files = {}
        for name, arr in arrays.items():
            np.save(tmp / name, arr, allow_pickle=False)
            files[name] = _sha256_file(tmp / name)
        (tmp / "dem.txt").write_text(dem_text, encoding="utf-8")
        files["dem.txt"] = _sha256_file(tmp / "dem.txt")
        manifest = {
            "schema": CORPUS_SCHEMA,
            "problem": problem,
            "problem_id": problem["id"],
            "problem_sha256": hashlib.sha256(_canonical_json(problem)).hexdigest(),
            "base_seed": int(base_seed),
            "shot_seed": int(shot_seed),
            "shots": int(shots),
            "num_detectors": m,
            "num_mechanisms": int(Hc.shape[1]),
            "num_observables": int(Oc.shape[0]),
            "dem_sha256": _sha256_bytes(dem_text.encode()),
            "generator": generator,
            "versions": versions(),
            "files": files,
        }
        manifest.update(extra)
        (tmp / _MANIFEST).write_bytes(_canonical_json(manifest))
        if dest.exists():
            shutil.rmtree(dest)
        os.replace(tmp, dest)
    except BaseException:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    return Corpus(problem, Hc, Oc, priors, det_round, dets, obs, dem_text, manifest, path=dest)


def _write_entry(dest: Path, problem: dict, base_seed: int, shots: int, generator: dict) -> Corpus:
    """Build a full (possibly loss) problem entry: circuit, DEM, arrays, seeded shots."""
    import stim

    circuit, heralds = circuits.build_circuit_and_heralds(problem)
    dem = circuits.circuit_dem(circuit, problem)
    dem_text = str(dem) + "\n"
    # H, O and priors always come from the DEM text, exactly as the reference construction derives
    # them.
    H, O, priors = dem_to_arrays(stim.DetectorErrorModel(dem_text))
    m = int(circuit.num_detectors)
    k = int(circuit.num_observables)
    if H.shape[0] != m:
        raise CorpusError(f"{problem['id']}: DEM has {H.shape[0]} detectors, circuit has {m}")
    if O.shape[0] != k:
        raise CorpusError(f"{problem['id']}: DEM has {O.shape[0]} observables, circuit has {k}")
    det_round = circuits.detector_rounds(problem, circuit, heralds)

    shot_seed = circuits.derive_seed(base_seed, "dev", problem["id"], "latency")
    dets_packed, obs_packed = circuits.sample_shots(circuit, shots, shot_seed)
    dets = np.unpackbits(dets_packed, axis=1, count=m, bitorder="little").astype(np.uint8)
    obs = np.unpackbits(obs_packed, axis=1, count=k, bitorder="little").astype(np.uint8) \
        if k else np.zeros((shots, 0), dtype=np.uint8)

    extra = {"kind": "full", "loss": problem.get("loss")}
    return _write_files(dest, problem, base_seed, shot_seed, shots, canonical_csc(H),
                        canonical_csc(O), priors, det_round, dets, obs, dem_text, extra, generator)


def _write_window_entry(dest: Path, problem: dict, base_seed: int, shots: int,
                        parent: Corpus, generator: dict) -> Corpus:
    """Derive a window entry from its parent's stored entry (the reference construction's window
    rule)."""
    shape = problem["shape"]
    wanted = min(int(shots), parent.shots)
    if wanted <= 0:
        raise CorpusError(f"{problem['id']}: window has no shots")
    H_w, O_w, priors_w, rows, cols = extract_window(
        parent.H, parent.O, parent.priors, parent.det_round, shape["start_round"], shape["w"])
    dets = np.ascontiguousarray(parent.dets[:wanted][:, rows])
    obs = np.ascontiguousarray(parent.obs[:wanted])
    det_round = parent.det_round[rows]
    dem_text = arrays_to_dem_text(H_w, O_w, priors_w)
    shot_seed = int(parent.manifest["shot_seed"])
    extra = {
        "kind": "window",
        "parent": shape["parent"],
        "parent_problem_sha256": parent.manifest["problem_sha256"],
        "window": {"start_round": int(shape["start_round"]), "w": int(shape["w"]),
                   "commit": int(shape["commit"]),
                   "rows": [int(x) for x in rows], "cols": [int(x) for x in cols]},
    }
    return _write_files(dest, problem, base_seed, shot_seed, wanted, H_w, O_w, priors_w,
                        det_round, dets, obs, dem_text, extra, generator)


def load_entry(dest: Path) -> Corpus:
    """Load and validate a corpus entry; raises CorpusError when it is absent or inconsistent."""
    dest = Path(dest)
    manifest_path = dest / _MANIFEST
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise CorpusError(f"{dest}: cannot read {_MANIFEST}: {exc}") from exc
    except ValueError as exc:
        raise CorpusError(f"{dest}: {_MANIFEST} is not valid JSON: {exc}") from exc
    if not isinstance(manifest, dict) or manifest.get("schema") != CORPUS_SCHEMA:
        raise CorpusError(f"{dest}: {_MANIFEST} schema is not {CORPUS_SCHEMA}")
    files = manifest.get("files")
    if not isinstance(files, dict):
        raise CorpusError(f"{dest}: {_MANIFEST} has no files object")
    for name, digest in files.items():
        path = dest / name
        if not path.is_file():
            raise CorpusError(f"{dest}: missing {name}")
        if _sha256_file(path) != digest:
            raise CorpusError(f"{dest}: {name} does not match its manifest")
    try:
        H = _load_csc(dest, "H.indptr.npy", "H.indices.npy", manifest["num_detectors"],
                      manifest["num_mechanisms"])
        O = _load_csc(dest, "O.indptr.npy", "O.indices.npy", manifest["num_observables"],
                      manifest["num_mechanisms"])
        priors = np.load(dest / "priors.npy", allow_pickle=False)
        det_round = np.load(dest / "det_round.npy", allow_pickle=False)
        dets = np.load(dest / "dets.npy", allow_pickle=False)
        obs = np.load(dest / "obs.npy", allow_pickle=False)
        dem_text = (dest / "dem.txt").read_text(encoding="utf-8")
    except (OSError, ValueError, KeyError) as exc:
        raise CorpusError(f"{dest}: cannot load arrays: {exc}") from exc
    shots = int(manifest["shots"])
    m, n, k = manifest["num_detectors"], manifest["num_mechanisms"], manifest["num_observables"]
    if priors.shape != (n,) or det_round.shape != (m,) \
            or dets.shape != (shots, m) or obs.shape != (shots, k):
        raise CorpusError(f"{dest}: array shapes do not match the manifest")
    problem = manifest.get("problem")
    if not isinstance(problem, dict) or problem.get("id") != manifest.get("problem_id"):
        raise CorpusError(f"{dest}: {_MANIFEST} has no problem object")
    if hashlib.sha256(_canonical_json(problem)).hexdigest() != manifest.get("problem_sha256"):
        raise CorpusError(f"{dest}: problem object does not match its SHA-256")
    return Corpus(problem, H, O, priors, det_round, dets, obs, dem_text, manifest,
                  path=dest, from_cache=True)


def _load_csc(dest: Path, indptr_name: str, indices_name: str, rows: int, cols: int):
    import scipy.sparse as sp

    indptr = np.load(dest / indptr_name, allow_pickle=False).astype(np.int32)
    indices = np.load(dest / indices_name, allow_pickle=False).astype(np.int32)
    if indptr.shape != (cols + 1,) or int(indptr[-1]) != indices.shape[0]:
        raise CorpusError(f"{dest}: inconsistent {indptr_name}/{indices_name}")
    matrix = sp.csc_matrix((np.ones(indices.shape[0], dtype=np.uint8), indices, indptr),
                           shape=(rows, cols), dtype=np.uint8)
    return canonical_csc(matrix)


def ensure_corpus(cache_root, problem: dict, base_seed: int, shots: int, *,
                  parent: dict | None = None, parent_shots: int | None = None,
                  log=None) -> Corpus:
    """Return the cached corpus entry, building it on first use.

    A window problem needs its parent problem object and the parent's shot count for the mode;
    the window reuses the parent's entry and takes the first min(shots, parent shots) shots."""
    is_window = problem.get("shape", {}).get("kind") == "window"
    expected = int(shots)
    if is_window:
        if parent is None or parent_shots is None:
            raise CorpusError(f"{problem['id']}: a window needs its parent and the parent's shots")
        expected = min(int(shots), int(parent_shots))
    generator = generator_versions()
    dest = corpus_dir(cache_root, problem, base_seed, shots, generator)
    if dest.is_dir():
        try:
            corpus = load_entry(dest)
            if corpus.id != problem["id"] or corpus.shots != expected:
                raise CorpusError(f"{dest}: manifest does not describe {problem['id']} / "
                                  f"{expected} shots")
            if corpus.manifest.get("generator") != generator:
                raise CorpusError(f"{dest}: built with {corpus.manifest.get('generator')}, "
                                  f"not with the installed {generator}")
            if log:
                log(f"corpus: reusing {corpus.describe()} ({describe_generator(generator)})")
            return corpus
        except CorpusError as exc:
            if log:
                log(f"corpus: rebuilding {problem['id']} ({exc})")
    dest.parent.mkdir(parents=True, exist_ok=True)
    if log:
        log(f"corpus: building {problem['id']} ({expected} shots, "
            f"{describe_generator(generator)})")
    if is_window:
        parent_corpus = ensure_corpus(cache_root, parent, base_seed, int(parent_shots), log=log)
        return _write_window_entry(dest, problem, base_seed, shots, parent_corpus, generator)
    return _write_entry(dest, problem, base_seed, shots, generator)
